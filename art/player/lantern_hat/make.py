def compose(parts):
    """parts: list of (layer, dx, dy). Later parts paint over earlier ones."""
    g = [['.'] * W for _ in range(H)]
    for (y0, rows), dx, dy in parts:
        for j, r in enumerate(rows):
            for i, c in enumerate(r):
                if c == '.':
                    continue
                x, y = i + dx, y0 + j + dy
                assert 0 <= x < W and 0 <= y < H
                g[y][x] = c
    return g


def idle_frames():
    # head sinks 1px into the collar (breathing); the lure follows a frame late
    head_dy = [0, 1, 1, 0]
    hang_dy = [0, 0, 1, 1]
    out = []
    for f in range(4):
        out.append(compose([
            (F_FEET, 0, 0),
            (F_ROBE, 0, 0),
            (F_HEAD, 0, head_dy[f]),
            (HANG_TWINKLE if f == 2 else HANG, 0, hang_dy[f]),
            (F_WAND, 0, 0),
        ]))
    return out


def walk_frames():
    body_dy = [0, -1, 0, -1]
    hang_dy = [-1, 0, -1, 0]      # previous frame's body_dy
    out = []
    for f in range(4):
        out.append(compose([
            (S_FEET[f], 0, 0),
            (S_ROBE, 0, body_dy[f]),
            (S_HEAD, 0, body_dy[f]),
            (HANG, 0, hang_dy[f]),
            (S_ARM, 0, body_dy[f]),
        ]))
    return out


def to_img(g):
    im = Image.new('RGBA', (W, H), (0, 0, 0, 0))
    px = im.load()
    for y in range(H):
        for x in range(W):
            c = PALETTE[g[y][x]]
            if c:
                px[x, y] = rgba(c)
    return im


def on_bg(im, scale):
    big = im.resize((W * scale, H * scale), Image.NEAREST)
    out = Image.new('RGBA', big.size, BG)
    out.alpha_composite(big)
    return out


def main():
    frames = [to_img(g) for g in idle_frames() + walk_frames()]

    sheet = Image.new('RGBA', (W * 8, H), (0, 0, 0, 0))
    for i, im in enumerate(frames):
        sheet.paste(im, (i * W, 0))
    sheet.save(os.path.join(HERE, 'sheet.png'))

    gap, s1, s2 = 8, 8, 2
    pw = gap + 8 * (W * s1 + gap)
    ph = gap + H * s1 + gap + H * s2 + gap
    prev = Image.new('RGBA', (pw, ph), BG)
    for i, im in enumerate(frames):
        prev.alpha_composite(on_bg(im, s1), (gap + i * (W * s1 + gap), gap))
        prev.alpha_composite(on_bg(im, s2), (gap + i * (W * s2 + gap), gap + H * s1 + gap))
    prev.save(os.path.join(HERE, 'preview.png'))

    for name, fr in (('idle', frames[:4]), ('walk', frames[4:])):
        gf = [on_bg(im, 8).convert('RGB') for im in fr]
        gf[0].save(os.path.join(HERE, name + '.gif'), save_all=True,
                   append_images=gf[1:], duration=150, loop=0, disposal=1)

    used = set()
    for im in frames:
        used |= {c for _, c in im.getcolors(1024) if c[3]}
    print('frames:', len(frames), 'colors used:', len(used))
    for i, im in enumerate(frames):
        print(i, 'bbox', im.getbbox())


if __name__ == '__main__':
    main()
