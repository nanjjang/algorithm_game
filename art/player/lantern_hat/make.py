"""등불 모자 (Lantern Hat) wizard - player sprite generator.

Every pixel is authored by hand as ASCII rows (one char = one pixel).
A frame is a stack of small hand-drawn layers (feet, robe, head+hat, hanging
lure, wand/arm) pasted at integer offsets; nothing is scaled, rotated or
procedurally drawn.  Run:  python3 make.py
"""
