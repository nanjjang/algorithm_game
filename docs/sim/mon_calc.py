# --- 8.2 서리밭 위 (이동 -30%) ---
SLOW = 0.7
print('== 8.2 서리밭 위 ==')
print('느려진 자세 속도:', {k: round(v * SLOW, 2) for k, v in sp.items()})
for n, d, t in [('얼음 기둥', 1.15, 0.8), ('뿔 휘두르기(예고 1.2로 늘림)', 2.221, 1.2), ('뿔 돌진', 0.95, 0.9)]:
    need = 0.25 + d / (V * SLOW)
    print(n, '걸리는 시간 %.2f' % need, '예고', t, '여유 %.2f' % (t - need))
HORN_WALK, HORN_WALK_ON_FROST = 3.0, 2.4
print('R2 흰뿔 걷는 속도: 평소', HORN_WALK, '< V', V, '->', HORN_WALK < V)
print('R2 서리밭 위: 3.0이면 따라잡히는 캐릭터', [k for k, v in sp.items() if v * SLOW <= HORN_WALK])
print('R2 서리밭 위: 2.4로 내리면 따라잡히는 캐릭터', [k for k, v in sp.items() if v * SLOW <= HORN_WALK_ON_FROST],
      '속도 차 %.2f' % (V * SLOW - HORN_WALK_ON_FROST))

