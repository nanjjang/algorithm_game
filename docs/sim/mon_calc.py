# --- 3.7 / 8.4 서리 숨결의 탄 사이와 줄기 속도 ---
print('== 서리 숨결 (초당 4발, 초당 45도, 속도 5.5) ==')
rate = 4
for d in (2, 3, 4, 5, 6, 8):
    dth = math.radians(45 / rate)
    dr = 5.5 / rate
    print('거리', d, '탄 사이 %.2f' % math.hypot(dr, d * dth), '줄기가 옆으로 움직이는 속도 %.2f' % (d * math.radians(45)))
