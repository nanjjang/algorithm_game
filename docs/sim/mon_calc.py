# --- 4.2 체력 배율, 4.3 예산 ---
def H(w): return 1 + 0.12 * (w - 1) if w <= 12 else 2.32 * 1.06 ** (w - 12)
def B(w): return 10 + 6 * w if w <= 12 else min(200, 82 + 4 * (w - 12))
print('== 4.2 H(w) ==', [(w, round(H(w), 2)) for w in (1, 6, 10, 12, 20, 30, 40, 50, 60, 80, 100)])

# --- 4.8 점수의 참고 크기 (처치 + 클리어 + 무피격만) ---
def S(w): return 1 + 0.1 * (w - 1)
def sc(w):
    if w % 10 == 0:
        return (3000 + 200 + 100) * S(w)
    return (B(w) * 10 + 200 + 100) * S(w)
print('== 4.8 점수 크기 ==', [(n, round(sum(sc(w) for w in range(1, n + 1)))) for n in (9, 14, 30, 60)])

# --- 4.7 건너뛴 웨이브의 점수 (정수 계산: S는 10배 한 정수 9 + w) ---
def base(w): return 3200 if w % 10 == 0 else B(w) * 10 + 200
print('== 4.7 건너뛴 점수 ==')
for n in (10, 20, 30, 40, 50):
    skipped = sum(base(w) * (9 + w) * 6 // 100 for w in range(1, n + 1))
    direct = sum(base(w) * (9 + w) // 10 for w in range(1, n + 1))
    print('건너뛴 웨이브', n, '받는 점수', skipped, '직접 넘긴 기본값', direct)

