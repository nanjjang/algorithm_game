using System;
using System.Collections.Generic;
using System.IO;
using System.Linq;
using System.Security.Cryptography;
using System.Text;

namespace Wizard.VersionStamp
{
    // DECISIONS-TECH T-18, CONTRACTS 3.2. SimVersion.CoreVersion = 재실행에 영향을 주는 소스의 SHA-256 앞 16바이트(hex 32자).
    // 대상: src/Wizard.Core/** 에서 Errors/ 밖의 .cs (Generated/ 의 표 포함),
    //       src/Wizard.Content/** 에서 Rules/ 밖의 .cs,
    //       src/Wizard.Sim/** 에서 Generated/SimVersion.g.cs 밖의 .cs.
    // 해시 입력: 경로 오름차순(서수)으로 파일마다 [UTF-8 상대 경로, 0x00, 줄 끝을 LF 로 맞춘 UTF-8 내용(BOM 제거), 0x00].
    //   versionstamp           SimVersion.g.cs 를 다시 쓴다
    //   versionstamp --check   다시 만든 결과가 커밋된 파일과 같은지 본다(다르면 1)
    //   versionstamp --print   값만 찍는다
    // 저장소 뿌리를 자기 위치에서 구하고 src/ 만 훑는다(.claude/worktrees/ 의 사본을 세지 않는다).
    public static class Program
    {
        public const string OutputRelative = "src/Wizard.Sim/Generated/SimVersion.g.cs";

        public static int Main(string[] args)
        {
            string root = RepoRoot.Find();
            string version = Compute(root);
            if (args.Contains("--print"))
            {
                Console.WriteLine(version);
                return 0;
            }
            string path = Path.Combine(root, OutputRelative);
            byte[] bytes = new UTF8Encoding(false).GetBytes(Render(version));
            if (args.Contains("--check"))
            {
                if (!File.Exists(path) || !File.ReadAllBytes(path).AsSpan().SequenceEqual(bytes))
                {
                    Console.Error.WriteLine($"FAIL  {OutputRelative} is stale (expected CoreVersion {version}). Run tools/Wizard.VersionStamp.");
                    return 1;
                }
                return 0;
            }
            Directory.CreateDirectory(Path.GetDirectoryName(path)!);
            File.WriteAllBytes(path, bytes);
            Console.WriteLine($"wrote {OutputRelative} ({version})");
            return 0;
        }

        public static IReadOnlyList<string> SourceFiles(string root)
        {
            var files = new List<string>();
            Collect(root, "src/Wizard.Core", rel => !rel.StartsWith("src/Wizard.Core/Errors/", StringComparison.Ordinal), files);
            Collect(root, "src/Wizard.Content", rel => !rel.StartsWith("src/Wizard.Content/Rules/", StringComparison.Ordinal), files);
            Collect(root, "src/Wizard.Sim", rel => !string.Equals(rel, OutputRelative, StringComparison.Ordinal), files);
            files.Sort(StringComparer.Ordinal);
            return files;
        }

        public static string Compute(string root)
        {
            using var sha = IncrementalHash.CreateHash(HashAlgorithmName.SHA256);
            var zero = new byte[] { 0 };
            foreach (string rel in SourceFiles(root))
            {
                sha.AppendData(Encoding.UTF8.GetBytes(rel));
                sha.AppendData(zero);
                string text = File.ReadAllText(Path.Combine(root, rel), Encoding.UTF8).Replace("\r\n", "\n", StringComparison.Ordinal);
                if (text.Length > 0 && text[0] == '﻿')
                {
                    text = text.Substring(1);
                }
                sha.AppendData(Encoding.UTF8.GetBytes(text));
                sha.AppendData(zero);
            }
            byte[] digest = sha.GetHashAndReset();
            return Convert.ToHexString(digest, 0, 16).ToLowerInvariant();
        }

        private static void Collect(string root, string relDir, Func<string, bool> include, List<string> into)
        {
            string abs = Path.Combine(root, relDir);
            if (!Directory.Exists(abs))
            {
                return;
            }
            foreach (string file in Directory.EnumerateFiles(abs, "*.cs", SearchOption.AllDirectories))
            {
                string rel = Path.GetRelativePath(root, file).Replace('\\', '/');
                if (rel.Contains("/bin/", StringComparison.Ordinal) || rel.Contains("/obj/", StringComparison.Ordinal))
                {
                    continue;
                }
                if (include(rel))
                {
                    into.Add(rel);
                }
            }
        }

        private static string Render(string version) =>
            "// <auto-generated>\n" +
            "// tools/Wizard.VersionStamp 이 만든 파일이다. 손으로 고치지 않는다. 코어 소스를 고치면 다시 만들어 같이 커밋한다(T-41).\n" +
            "// </auto-generated>\n" +
            "namespace Wizard.Sim\n" +
            "{\n" +
            "    public static partial class SimVersion\n" +
            "    {\n" +
            "        // 재실행에 영향을 주는 소스(T-18의 대상 목록) SHA-256의 앞 16바이트(hex 32자)\n" +
            $"        public const string CoreVersion = \"{version}\";\n" +
            "    }\n" +
            "}\n";
    }

    internal static class RepoRoot
    {
        public static string Find()
        {
            string? dir = AppContext.BaseDirectory;
            while (dir != null)
            {
                if (File.Exists(Path.Combine(dir, "Wizard.sln")))
                {
                    return dir;
                }
                dir = Path.GetDirectoryName(dir.TrimEnd(Path.DirectorySeparatorChar));
            }
            throw new InvalidOperationException("Wizard.sln not found above " + AppContext.BaseDirectory);
        }
    }
}
